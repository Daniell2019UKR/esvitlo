import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createAddressWatch} from './address-watch.js';

test('saved addresses send updates once, require two clear checks and unsubscribe',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'address-watch-'));
 t.after(()=>rm(dir,{recursive:true,force:true}));
 let clock=0;
 let result={status:'active',startedAt:'12:00',estimatedRestoration:'17:00'};
 const sent=[];
 const options={dir,now:()=>clock,lookup:async()=>result,send:async(token,data)=>sent.push({token,...data})};
 let watch=await createAddressWatch(options);
 const key='Bearer '+'a'.repeat(64),token='test-'.repeat(20);
 const input={token,places:[{id:'home',region:'lviv',city:'Львів',street:'Тестова',house:'9'}]};
 assert.equal(await watch.update('wrong',input),401);
 assert.equal(await watch.update(key,input),204);
 const step=async()=>{await watch.tick();clock+=300000;};
 await step();
 watch=await createAddressWatch(options);
 await step();
 assert.equal(sent.length,1);
 result={...result,estimatedRestoration:'18:00'};
 await step();
 result={status:'no_emergency'};
 await step();
 result={status:'unavailable'};
 await step();
 result={status:'no_emergency'};
 await step();
 assert.equal(sent.length,2);
 await step();
 assert.equal(sent.length,3);
 assert.match(sent[2].body,/більше не повідомляє/u);
 assert.ok(sent.every(item=>!item.body.includes('Тестова')&&item.id==='home'));
 assert.equal(await watch.update(key,{places:[]}),204);
 assert.equal(await readFile(join(dir,'address-watch.json'),'utf8'),'[]');
});
